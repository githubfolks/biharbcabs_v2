export interface ConversationState {
  phone: string;
  state: string;
  role: 'CUSTOMER' | 'DRIVER' | 'ADMIN';
  context_data: Record<string, any>;
}

/**
 * Get or initialize conversation session for a phone number.
 */
export async function getConversation(phone: string): Promise<ConversationState> {
  const cleanPhone = phone.replace(/\D/g, '');
  const res = await query(
    `SELECT phone, state, role, context_data 
     FROM crm_whatsapp_conversations 
     WHERE phone = $1`,
    [cleanPhone]
  );

  if (res.rows.length > 0) {
    return res.rows[0];
  }

  // Check if phone belongs to a registered driver
  const driverCheck = await query(
    `SELECT id FROM crm_drivers WHERE phone = $1 OR whatsapp_phone = $1`,
    [cleanPhone]
  );

  const role = driverCheck.rows.length > 0 ? 'DRIVER' : 'CUSTOMER';

  await query(
    `INSERT INTO crm_whatsapp_conversations (phone, state, role, context_data, updated_at)
     VALUES ($1, 'IDLE', $2, '{}'::jsonb, CURRENT_TIMESTAMP)
     ON CONFLICT (phone) DO NOTHING`,
    [cleanPhone, role]
  );

  return {
    phone: cleanPhone,
    state: 'IDLE',
    role,
    context_data: {},
  };
}

/**
 * Update conversation state and context data.
 */
export async function updateConversation(
  phone: string,
  state: string,
  contextData: Record<string, any>,
  role?: 'CUSTOMER' | 'DRIVER' | 'ADMIN'
): Promise<void> {
  const cleanPhone = phone.replace(/\D/g, '');
  await query(
    `INSERT INTO crm_whatsapp_conversations (phone, state, role, context_data, last_message_at, updated_at)
     VALUES ($1, $2, COALESCE($4, 'CUSTOMER'), $3, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
     ON CONFLICT (phone) DO UPDATE
     SET state = EXCLUDED.state,
         role = COALESCE($4, crm_whatsapp_conversations.role),
         context_data = EXCLUDED.context_data,
         last_message_at = CURRENT_TIMESTAMP,
         updated_at = CURRENT_TIMESTAMP`,
    [cleanPhone, state, JSON.stringify(contextData), role || null]
  );
}

/**
 * Reset conversation state back to IDLE.
 */
export async function resetConversation(phone: string): Promise<void> {
  await updateConversation(phone, 'IDLE', {});
}

/**
 * Parse structured website pre-filled WhatsApp quotes.
 * Generated by BC_Calculator::build_whatsapp_url().
 * e.g. "Hi BiharCabs, I want to book a One-Way cab from Patna to Darbhanga on 2026-11-10 at 09:00 AM."
 */
export function parsePreFilledWebsiteMessage(text: string): {
  isWebsiteQuote: boolean;
  origin?: string;
  destination?: string;
  trip_type?: string;
  pickup_date?: string;
  pickup_time?: string;
  selected_vehicle?: string;
} {
  const lower = text.toLowerCase();

  // Pattern: ... from {origin} to {destination} on {date} ...
  const routeMatch = text.match(/from\s+([a-zA-Z\s]+)\s+to\s+([a-zA-Z\s]+?)(?:\s+on|\s+at|\.|\,|$)/i);
  const dateMatch = text.match(/on\s+(\d{4}-\d{2}-\d{2}|\d{1,2}[\/\-]\d{1,2}[\/\-]\d{2,4})/i);
  const timeMatch = text.match(/at\s+(\d{1,2}(?::\d{2})?\s*(?:am|pm)?)/i);

  let tripType = 'oneway';
  if (lower.includes('round-trip') || lower.includes('round trip')) {
    tripType = 'roundtrip';
  } else if (lower.includes('airport')) {
    tripType = 'airport';
  } else if (lower.includes('local') || lower.includes('8hr') || lower.includes('80km')) {
    tripType = 'local';
  }

  if (routeMatch) {
    const origin = routeMatch[1].trim();
    const destination = routeMatch[2].trim();
    return {
      isWebsiteQuote: true,
      origin,
      destination,
      trip_type: tripType,
      pickup_date: dateMatch ? dateMatch[1] : undefined,
      // No stated time: leave it blank so the bot asks the customer, never assume one.
      pickup_time: timeMatch ? timeMatch[1] : undefined,
    };
  }

  return { isWebsiteQuote: false };
}

const PICKUP_TIME_PROMPT =
  'When do you need the cab?\nReply *NOW*, or a time like *today 6:30 pm*, *tomorrow 9 am* or *12/11 7 pm*.';

